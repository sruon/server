describe('Synergy recipes', function()
    it('looks up a recipe by id', function()
        local recipe = GetSynergyRecipeByID(2)
        assert(recipe ~= nil, 'recipe 2 is missing')
        assert(recipe.resultName == 'Excalipoor II', 'wrong name')
        assert(recipe.result == xi.item.EXCALIPOOR_II and recipe.resultQty == 1, 'wrong result')
        assert(recipe.resultHQ3 == xi.item.EXCALIPOOR_II and recipe.resultHQ3Qty == 1, 'wrong high quality result')
        assert(recipe.ingredient1 == xi.item.EXCALIPOOR and recipe.ingredient2 == xi.item.EXCALIPOOR, 'wrong ingredients')
        assert(recipe.ingredient3 == 0 and recipe.ingredient8 == 0, 'extra ingredients')
        assert(recipe.cost_light_fewell == 5 and recipe.cost_dark_fewell == 5, 'wrong fewell cost')
        assert(recipe.cost_fire_fewell == 0 and recipe.cost_lightning_fewell == 0, 'extra fewell cost')
        assert(recipe.primary_skill == 0 and recipe.primary_rank == xi.craftRank.AMATEUR, 'wrong synergy rank')
        assert(recipe.secondary_skill == 0 and recipe.tertiary_rank == 0, 'wrong support crafts')
    end)

    it('has no recipe for an unknown id', function()
        assert(GetSynergyRecipeByID(9999) == nil, 'recipe 9999 exists')
    end)
end)
