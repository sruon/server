describe('Pet data', function()
    it('names an avatar from the pet list', function()
        local player = xi.test.world:spawnPlayer({ zone = xi.zone.WEST_RONFAURE, job = xi.job.SMN, level = 75 })
        player:spawnPet(xi.petId.CAIT_SITH)
        assert(player:getPetName() == 'Cait Sith', string.format('got %s', player:getPetName()))
    end)

    it('names a wyvern from the pet names', function()
        local player = xi.test.world:spawnPlayer({ zone = xi.zone.WEST_RONFAURE, job = xi.job.DRG, level = 75 })
        player:setPetName(xi.petType.WYVERN, xi.petName.ROVER)
        player:spawnPet(xi.petId.WYVERN)
        assert(player:getPetName() == 'Rover', string.format('got %s', player:getPetName()))
    end)

    it('names an automaton from the pet names', function()
        local player = xi.test.world:spawnPlayer({ zone = xi.zone.WEST_RONFAURE, job = xi.job.PUP, level = 75 })
        player:setPetName(xi.petType.AUTOMATON, xi.petName.MK_IV)
        assert(player:getAutomatonName() == 'Mk.IV', string.format('got %s', player:getAutomatonName()))
    end)
end)
